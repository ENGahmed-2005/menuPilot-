export const ROLE_HOME = {
  owner: "/owner/dashboard",
  kitchen: "/kitchen",
  cashier: "/cashier/tables",
  waiter: "/waiter",
  admin: "/admin/dashboard",
};

export function getRoleHome(role) {
  return ROLE_HOME[role] || "/";
}
