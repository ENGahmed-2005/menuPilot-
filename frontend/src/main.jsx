/* ==========================================================================
   main.jsx — نقطة البداية لتطبيق React
   --------------------------------------------------------------------------
   هذا أول ملف JavaScript يشتغل في المتصفح. مهمته الوحيدة:
   "خُذ مكوّن App وارسمه داخل العنصر <div id="root"> الموجود في index.html".
   ========================================================================== */

// import: نجلب أدوات من مكتبات خارجية أو من ملفات مشروعنا.
import React from "react";

// createRoot: الدالة التي تربط React بعنصر HTML حقيقي في الصفحة.
// نجلبها من "react-dom/client" لأن react-dom هو الجزء المسؤول عن المتصفح.
import { createRoot } from "react-dom/client";

// المكوّن الرئيسي لتطبيقنا. لاحظ الاسم بحرف كبير App — كل مكوّن React
// يجب أن يبدأ بحرف كبير حتى يميّزه React عن وسوم HTML العادية (div, span...).
import App from "./App.jsx";

// استيراد ملف CSS مباشرة: Vite يفهم هذا ويضيف الستايل إلى الصفحة تلقائيًا.
// لا يوجد متغيّر نستقبله هنا لأننا نريد التأثير فقط (الستايل).
import "./index.css";

// 1) document.getElementById("root") → نبحث عن <div id="root"> في index.html
// 2) createRoot(...) → نُنشئ "جذر" React داخل ذلك العنصر
// 3) .render(...) → نطلب من React رسم شجرة المكوّنات
createRoot(document.getElementById("root")).render(
  // StrictMode: وضع صارم للتطوير فقط (يختفي في نسخة الإنتاج).
  // ينبّهك للأخطاء الشائعة، ويستدعي بعض الدوال مرتين عن قصد
  // ليكشف الأخطاء المخفية. لذلك إن رأيت شيئًا يحدث مرتين أثناء
  // التطوير فهذا طبيعي وليس خطأً في كودك.
  <React.StrictMode>
    {/* هكذا نستخدم مكوّنًا: نكتبه كأنه وسم HTML. */}
    <App />
  </React.StrictMode>
);
